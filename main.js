// INIT
// ============================
document.addEventListener("DOMContentLoaded", function() {

    // -- Close modal --
    var closeBtn = document.getElementById("modal-close-btn");
    if (closeBtn) {
        closeBtn.onclick = closeModal;
    }
    var modalBg = document.getElementById("modal");
    if (modalBg) {
        modalBg.onclick = function(e) {
            if (e.target === modalBg) closeModal();
        };
    }
    document.onkeydown = function(e) {
        if (e.key === "Escape") closeModal();
    };

    // -- Language Toggle --
    var langBtn = document.getElementById("lang-toggle");
    if (langBtn) {
        langBtn.onclick = function() {
            currentLang = currentLang === "ar" ? "en" : "ar";
            langBtn.textContent = currentLang === "ar" ? "EN" : "\u0639\u0631\u0628\u064A";
            document.documentElement.lang = currentLang;
            document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";
            var els = document.querySelectorAll("[data-i18n]");
            for (var i = 0; i < els.length; i++) {
                var key = els[i].getAttribute("data-i18n");
                if (translations[currentLang][key]) {
                    els[i].textContent = translations[currentLang][key];
                }
            }
        };
    }

    // -- Hamburger --
    var ham = document.getElementById("hamburger");
    var navLinks = document.getElementById("nav-links");
    if (ham && navLinks) {
        ham.onclick = function() {
            navLinks.classList.toggle("open");
        };
        var links = navLinks.querySelectorAll("a");
        for (var i = 0; i < links.length; i++) {
            links[i].onclick = function() {
                navLinks.classList.remove("open");
            };
        }
    }

    // -- Navbar scroll --
    var navbar = document.getElementById("navbar");
    window.onscroll = function() {
        // Navbar
        if (window.scrollY > 60) {
            navbar.className = "navbar scrolled";
        } else {
            navbar.className = "navbar";
        }
        // Progress bar
        var scrollTop = window.scrollY;
        var docH = document.documentElement.scrollHeight - window.innerHeight;
        var progress = document.getElementById("scroll-progress");
        if (progress && docH > 0) {
            progress.style.width = ((scrollTop / docH) * 100) + "%";
        }
        // Back to top
        var topBtn = document.getElementById("topBtn");
        if (topBtn) {
            topBtn.style.display = scrollTop > 500 ? "block" : "none";
        }
    };

    // -- Back to top --
    var topBtn = document.getElementById("topBtn");
    if (topBtn) {
        topBtn.onclick = function() {
            window.scrollTo({ top: 0, behavior: "smooth" });
        };
    }

    // -- Smooth scroll --
    var anchors = document.querySelectorAll('a[href^="#"]');
    for (var i = 0; i < anchors.length; i++) {
        anchors[i].onclick = function(e) {
            e.preventDefault();
            var href = this.getAttribute("href");
            if (href === "#") return;
            var target = document.querySelector(href);
            if (target) target.scrollIntoView({ behavior: "smooth" });
        };
    }

    // -- Counter Animation --
    var counted = false;
    var statNums = document.querySelectorAll(".stat-num");
    function checkCounters() {
        if (counted || statNums.length === 0) return;
        var firstStat = statNums[0];
        var rect = firstStat.getBoundingClientRect();
        if (rect.top < window.innerHeight && rect.bottom > 0) {
            counted = true;
            for (var i = 0; i < statNums.length; i++) {
                (function(el) {
                    var target = parseInt(el.getAttribute("data-count")) || 0;
                    var current = 0;
                    var step = Math.max(1, Math.floor(target / 50));
                    var timer = setInterval(function() {
                        current += step;
                        if (current >= target) {
                            current = target;
                            clearInterval(timer);
                        }
                        el.textContent = current.toLocaleString();
                    }, 30);
                })(statNums[i]);
            }
        }
    }
    window.addEventListener("scroll", checkCounters);
    checkCounters();

});

